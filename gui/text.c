void text_draw_char(uint32_t x, uint32_t y, char c, uint32_t color) {
    uint8_t *glyph = (uint8_t *)font_data[(uint8_t)c];
    
    for (int row = 0; row < 8; row++) {
        uint8_t byte = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (byte & (1 << (7 - col))) {
                gui_draw_pixel(x + col, y + row, color);
            }
        }
    }
}

void text_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t color) {
    uint32_t pos_x = x;
    for (int i = 0; str[i]; i++) {
        text_draw_char(pos_x, y, str[i], color);
        pos_x += 8;
    }
}
